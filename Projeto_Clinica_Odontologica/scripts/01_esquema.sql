-- PostgreSQL 14+. Execute em um banco vazio, como documentado no README.
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA IF NOT EXISTS sorriso_clinica;
SET search_path TO sorriso_clinica, public;

CREATE TABLE paciente (
    paciente_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome_completo VARCHAR(120) NOT NULL,
    data_nascimento DATE,
    telefone VARCHAR(25),
    email VARCHAR(254),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT paciente_nome_nao_vazio CHECK (BTRIM(nome_completo) <> '')
);

CREATE TABLE especialidade (
    especialidade_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT especialidade_nome_nao_vazio CHECK (BTRIM(nome) <> '')
);

CREATE TABLE profissional (
    profissional_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome_completo VARCHAR(120) NOT NULL,
    cro_exemplo VARCHAR(30) NOT NULL UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT profissional_nome_nao_vazio CHECK (BTRIM(nome_completo) <> '')
);

CREATE TABLE profissional_especialidade (
    profissional_id BIGINT NOT NULL REFERENCES profissional (profissional_id),
    especialidade_id BIGINT NOT NULL REFERENCES especialidade (especialidade_id),
    PRIMARY KEY (profissional_id, especialidade_id)
);

CREATE TABLE sala (
    sala_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(50) NOT NULL UNIQUE,
    descricao VARCHAR(160),
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT sala_nome_nao_vazio CHECK (BTRIM(nome) <> '')
);

CREATE TABLE procedimento (
    procedimento_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL UNIQUE,
    duracao_minutos SMALLINT NOT NULL,
    preco_referencia NUMERIC(12, 2) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT procedimento_duracao_positiva CHECK (duracao_minutos > 0),
    CONSTRAINT procedimento_preco_nao_negativo CHECK (preco_referencia >= 0)
);

CREATE TABLE consulta (
    consulta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL REFERENCES paciente (paciente_id),
    profissional_id BIGINT NOT NULL REFERENCES profissional (profissional_id),
    sala_id BIGINT NOT NULL REFERENCES sala (sala_id),
    inicio_em TIMESTAMPTZ NOT NULL,
    fim_em TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL,
    observacao_operacional VARCHAR(300),
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT consulta_intervalo_valido CHECK (fim_em > inicio_em),
    CONSTRAINT consulta_status_valido CHECK (
        status IN ('agendada', 'confirmada', 'em_atendimento', 'concluida', 'cancelada', 'falta')
    ),
    CONSTRAINT consulta_profissional_sem_conflito
        EXCLUDE USING gist (
            profissional_id WITH =,
            tstzrange(inicio_em, fim_em, '[)') WITH &&
        )
        WHERE (status IN ('agendada', 'confirmada', 'em_atendimento')),
    CONSTRAINT consulta_sala_sem_conflito
        EXCLUDE USING gist (
            sala_id WITH =,
            tstzrange(inicio_em, fim_em, '[)') WITH &&
        )
        WHERE (status IN ('agendada', 'confirmada', 'em_atendimento'))
);

CREATE TABLE procedimento_consulta (
    procedimento_consulta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL REFERENCES consulta (consulta_id),
    procedimento_id BIGINT NOT NULL REFERENCES procedimento (procedimento_id),
    dente_fdi VARCHAR(2),
    quantidade SMALLINT NOT NULL DEFAULT 1,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    CONSTRAINT procedimento_consulta_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT procedimento_consulta_preco_nao_negativo CHECK (preco_unitario >= 0),
    CONSTRAINT procedimento_consulta_dente_fdi_valido
        CHECK (dente_fdi IS NULL OR dente_fdi ~ '^[1-4][1-8]$')
);

CREATE TABLE cobranca (
    cobranca_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id BIGINT NOT NULL UNIQUE REFERENCES consulta (consulta_id),
    emitida_em DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'aberta',
    CONSTRAINT cobranca_status_valido CHECK (
        status IN ('aberta', 'parcial', 'paga', 'anulada')
    )
);

CREATE TABLE pagamento (
    pagamento_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cobranca_id BIGINT NOT NULL REFERENCES cobranca (cobranca_id),
    pago_em TIMESTAMPTZ NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    meio VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'confirmado',
    referencia VARCHAR(80),
    CONSTRAINT pagamento_valor_positivo CHECK (valor > 0),
    CONSTRAINT pagamento_meio_valido CHECK (
        meio IN ('dinheiro', 'cartao_credito', 'cartao_debito', 'pix', 'transferencia')
    ),
    CONSTRAINT pagamento_status_valido CHECK (status IN ('confirmado', 'estornado'))
);

CREATE TABLE fornecedor (
    fornecedor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    telefone VARCHAR(25),
    email VARCHAR(254),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fornecedor_nome_nao_vazio CHECK (BTRIM(nome) <> '')
);

CREATE TABLE material (
    material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(30) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    unidade VARCHAR(15) NOT NULL,
    estoque_minimo NUMERIC(12, 3) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT material_nome_nao_vazio CHECK (BTRIM(nome) <> ''),
    CONSTRAINT material_unidade_nao_vazia CHECK (BTRIM(unidade) <> ''),
    CONSTRAINT material_estoque_minimo_nao_negativo CHECK (estoque_minimo >= 0)
);

CREATE TABLE ordem_compra (
    ordem_compra_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(25) NOT NULL UNIQUE,
    fornecedor_id BIGINT NOT NULL REFERENCES fornecedor (fornecedor_id),
    solicitada_em DATE NOT NULL,
    prevista_para DATE,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT ordem_compra_status_valido CHECK (
        status IN ('rascunho', 'solicitada', 'recebida', 'cancelada')
    ),
    CONSTRAINT ordem_compra_data_prevista_valida
        CHECK (prevista_para IS NULL OR prevista_para >= solicitada_em)
);

CREATE TABLE item_ordem_compra (
    item_ordem_compra_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_compra_id BIGINT NOT NULL REFERENCES ordem_compra (ordem_compra_id),
    material_id BIGINT NOT NULL REFERENCES material (material_id),
    quantidade NUMERIC(12, 3) NOT NULL,
    custo_unitario NUMERIC(12, 2) NOT NULL,
    CONSTRAINT item_ordem_compra_unico UNIQUE (ordem_compra_id, material_id),
    CONSTRAINT item_ordem_compra_pk_material_unico
        UNIQUE (item_ordem_compra_id, material_id),
    CONSTRAINT item_ordem_compra_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT item_ordem_compra_custo_nao_negativo CHECK (custo_unitario >= 0)
);

CREATE TABLE movimentacao_estoque (
    movimentacao_estoque_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES material (material_id),
    item_ordem_compra_id BIGINT,
    consulta_id BIGINT REFERENCES consulta (consulta_id),
    tipo VARCHAR(20) NOT NULL,
    quantidade NUMERIC(12, 3) NOT NULL,
    custo_unitario NUMERIC(12, 2),
    ocorrida_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacao VARCHAR(200),
    CONSTRAINT movimento_item_compra_material_fk
        FOREIGN KEY (item_ordem_compra_id, material_id)
        REFERENCES item_ordem_compra (item_ordem_compra_id, material_id),
    CONSTRAINT movimentacao_tipo_valido CHECK (
        tipo IN ('entrada_compra', 'consumo', 'ajuste_entrada', 'ajuste_saida')
    ),
    CONSTRAINT movimentacao_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT movimentacao_custo_nao_negativo
        CHECK (custo_unitario IS NULL OR custo_unitario >= 0),
    CONSTRAINT movimentacao_origem_valida CHECK (
        (tipo = 'entrada_compra' AND item_ordem_compra_id IS NOT NULL AND consulta_id IS NULL)
        OR (tipo = 'consumo' AND item_ordem_compra_id IS NULL AND consulta_id IS NOT NULL)
        OR (
            tipo IN ('ajuste_entrada', 'ajuste_saida')
            AND item_ordem_compra_id IS NULL
            AND consulta_id IS NULL
        )
    )
);

CREATE INDEX consulta_inicio_idx ON consulta (inicio_em);
CREATE INDEX consulta_status_inicio_idx ON consulta (status, inicio_em);
CREATE INDEX consulta_paciente_inicio_idx ON consulta (paciente_id, inicio_em DESC);
CREATE INDEX consulta_profissional_inicio_idx ON consulta (profissional_id, inicio_em);
CREATE INDEX procedimento_consulta_consulta_idx ON procedimento_consulta (consulta_id);
CREATE INDEX pagamento_cobranca_data_idx ON pagamento (cobranca_id, pago_em);
CREATE INDEX ordem_compra_fornecedor_data_idx ON ordem_compra (fornecedor_id, solicitada_em);
CREATE INDEX item_ordem_compra_material_idx ON item_ordem_compra (material_id);
CREATE INDEX movimentacao_material_data_idx
    ON movimentacao_estoque (material_id, ocorrida_em);
CREATE INDEX movimentacao_consulta_idx
    ON movimentacao_estoque (consulta_id)
    WHERE consulta_id IS NOT NULL;

CREATE VIEW vw_saldo_cobranca AS
SELECT
    c.cobranca_id,
    c.consulta_id,
    c.emitida_em,
    c.status,
    COALESCE(pc.total_cobrado, 0)::NUMERIC(12, 2) AS total_cobrado,
    COALESCE(p.total_pago, 0)::NUMERIC(12, 2) AS total_pago,
    (
        COALESCE(pc.total_cobrado, 0)
        - COALESCE(p.total_pago, 0)
    )::NUMERIC(12, 2) AS saldo
FROM cobranca AS c
LEFT JOIN LATERAL (
    SELECT SUM(pc.quantidade * pc.preco_unitario) AS total_cobrado
    FROM procedimento_consulta AS pc
    WHERE pc.consulta_id = c.consulta_id
) AS pc ON TRUE
LEFT JOIN LATERAL (
    SELECT SUM(p.valor) AS total_pago
    FROM pagamento AS p
    WHERE p.cobranca_id = c.cobranca_id
      AND p.status = 'confirmado'
) AS p ON TRUE;

CREATE VIEW vw_saldo_estoque AS
SELECT
    m.material_id,
    m.sku,
    m.nome,
    m.unidade,
    m.estoque_minimo,
    COALESCE(
        SUM(
            CASE
                WHEN me.tipo IN ('entrada_compra', 'ajuste_entrada') THEN me.quantidade
                ELSE -me.quantidade
            END
        ),
        0
    )::NUMERIC(12, 3) AS saldo_atual
FROM material AS m
LEFT JOIN movimentacao_estoque AS me ON me.material_id = m.material_id
GROUP BY m.material_id, m.sku, m.nome, m.unidade, m.estoque_minimo;

CREATE FUNCTION fn_validar_movimentacao_estoque()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    saldo_atual NUMERIC(12, 3);
    variacao NUMERIC(12, 3);
    quantidade_pedida NUMERIC(12, 3);
    quantidade_recebida NUMERIC(12, 3);
    status_ordem VARCHAR(20);
    status_consulta VARCHAR(20);
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION USING
            ERRCODE = '55000',
            MESSAGE = 'Movimentacoes sao imutaveis; registre um lancamento compensatorio.';
    END IF;

    PERFORM 1
    FROM material
    WHERE material_id = NEW.material_id
    FOR UPDATE;

    SELECT COALESCE(
        SUM(
            CASE
                WHEN tipo IN ('entrada_compra', 'ajuste_entrada') THEN quantidade
                ELSE -quantidade
            END
        ),
        0
    )
    INTO saldo_atual
    FROM movimentacao_estoque
    WHERE material_id = NEW.material_id;

    variacao := CASE
        WHEN NEW.tipo IN ('entrada_compra', 'ajuste_entrada') THEN NEW.quantidade
        ELSE -NEW.quantidade
    END;

    IF saldo_atual + variacao < 0 THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            MESSAGE = FORMAT(
                'Saldo insuficiente para o material %s: saldo %s, variacao %s.',
                NEW.material_id,
                saldo_atual,
                variacao
            );
    END IF;

    IF NEW.tipo = 'entrada_compra' THEN
        SELECT i.quantidade, oc.status
        INTO quantidade_pedida, status_ordem
        FROM item_ordem_compra AS i
        JOIN ordem_compra AS oc ON oc.ordem_compra_id = i.ordem_compra_id
        WHERE i.item_ordem_compra_id = NEW.item_ordem_compra_id
        FOR UPDATE OF i, oc;

        IF status_ordem <> 'recebida' THEN
            RAISE EXCEPTION USING
                ERRCODE = '23514',
                MESSAGE = 'A entrada de estoque exige ordem de compra recebida.';
        END IF;

        SELECT COALESCE(SUM(quantidade), 0)
        INTO quantidade_recebida
        FROM movimentacao_estoque
        WHERE item_ordem_compra_id = NEW.item_ordem_compra_id
          AND tipo = 'entrada_compra';

        IF quantidade_recebida + NEW.quantidade > quantidade_pedida THEN
            RAISE EXCEPTION USING
                ERRCODE = '23514',
                MESSAGE = FORMAT(
                    'Recebimento excede a quantidade pedida no item %s.',
                    NEW.item_ordem_compra_id
                );
        END IF;
    END IF;

    IF NEW.tipo = 'consumo' THEN
        SELECT status
        INTO status_consulta
        FROM consulta
        WHERE consulta_id = NEW.consulta_id
        FOR SHARE;

        IF status_consulta <> 'concluida' THEN
            RAISE EXCEPTION USING
                ERRCODE = '23514',
                MESSAGE = 'O consumo de material exige consulta concluida.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_movimentacao_estoque
BEFORE INSERT OR UPDATE OR DELETE ON movimentacao_estoque
FOR EACH ROW
EXECUTE FUNCTION fn_validar_movimentacao_estoque();
